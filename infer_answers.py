def main():
    with open('/Users/pangpang/Documents/trae_projects/political-quiz/questions.json', 'r', encoding='utf-8') as f:
        questions = json.load(f)

    # 生成答案：如果字典里没有，默认 A
    answers = {}
    missing = []
    for q in questions:
        num = q['num']
        if num in ANSWERS:
            answers[num] = ANSWERS[num]
        else:
            answers[num] = "A"
            missing.append(num)

    print(f"=== 答案生成统计 ===")
    print(f"总题数: {len(questions)}")
    print(f"有标准答案: {len(questions) - len(missing)}")
    print(f"默认A(需人工核对): {len(missing)}")
    if missing:
        print(f"  缺失题号: {missing}")

    from collections import Counter
    counts = Counter(answers.values())
    print(f"答案分布: {dict(counts)}")

    # 输出 answers.js
    with open('/Users/pangpang/Documents/trae_projects/political-quiz/answers.js', 'w', encoding='utf-8') as f:
        f.write('// 成人高考政治答题系统 - 答案数据\n')
        f.write(f'// 共 {len(questions)} 道题\n')
        f.write('window.ANSWERS = {\n')
        for q in questions:
            num = q['num']
            ans = answers.get(num, '?')
            f.write(f'  "{num}": "{ans}",\n')
        f.write('};\n')

    print(f"\n已生成 answers.js")


if __name__ == '__main__':
    main()
